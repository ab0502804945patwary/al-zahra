'use client'
import { useState, useMemo } from 'react'
import {
  X,
  Loader2,
  Trash2,
  Building2,
  FileCheck,
  PhoneCall,
  Users,
  Landmark,
  Sliders,
  Sparkles,
  RefreshCw
} from 'lucide-react'
import { createClient, isSupabaseConfigured } from '@/lib/supabase/client'
import { useRouter } from 'next/navigation'
import { Company } from '@/lib/types'
import CountrySelect from '@/components/ui/CountrySelect'

interface Props {
  company?: Company
  existingCompanies?: Company[]
  onClose: () => void
  onSave?: (savedCompany: Company) => void
  onDelete?: (id: string) => void
}

export function computeNextCompanyId(companies: Company[] = []): string {
  let maxNum = 800
  if (Array.isArray(companies)) {
    companies.forEach(c => {
      if (!c.company_id) return
      const match = c.company_id.match(/AZC\s*(\d+)/i)
      if (match) {
        const num = parseInt(match[1], 10)
        if (!isNaN(num) && num > maxNum) maxNum = num
      }
    })
  }
  return `AZC${maxNum + 1}`
}

export default function CompanyModal({ company, existingCompanies = [], onClose, onSave, onDelete }: Props) {
  const router = useRouter()
  const supabase = createClient()
  const [loading, setLoading] = useState(false)

  const autoGeneratedId = useMemo(() => {
    return computeNextCompanyId(existingCompanies)
  }, [existingCompanies])

  const [form, setForm] = useState<Record<string, string>>(() => {
    if (company) return { ...(company as any) }
    return {
      company_id: autoGeneratedId,
      country_of_origin: 'Saudi Arabia',
      entity_type: 'Trading License',
      account_status: 'Active',
      service_type: 'a2z',
    }
  })

  const set = (k: string, v: string) => setForm(p => ({ ...p, [k]: v }))

  function handleResetAutoId() {
    set('company_id', autoGeneratedId)
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault()
    setLoading(true)

    const finalId = form.id || company?.id || `comp-${Date.now()}`
    const finalPayload: Company = {
      ...form,
      id: finalId,
      company_id: form.company_id || autoGeneratedId,
      company_name: form.company_name || 'Untitled Entity',
      created_at: company?.created_at || '2026-01-01T00:00:00.000Z',
    } as unknown as Company

    if (isSupabaseConfigured) {
      try {
        if (company) {
          await supabase.from('companies').update(form).eq('id', company.id)
        } else {
          await supabase.from('companies').insert([form])
        }
      } catch (err) {
        console.log('Saved company locally:', err)
      }
    }

    if (onSave) {
      onSave(finalPayload)
    }

    router.refresh()
    onClose()
  }

  async function handleDelete() {
    if (!company) return
    if (!confirm('Are you sure you want to delete this company entity and all associated records?')) return
    if (isSupabaseConfigured) {
      try {
        await supabase.from('companies').delete().eq('id', company.id)
      } catch (err) {
        console.log('Deleted locally:', err)
      }
    }

    if (onDelete) {
      onDelete(company.id)
    }

    router.refresh()
    onClose()
  }

  const SPAN: Record<number, string> = {
    12: 'sm:col-span-2 lg:col-span-12',
    6: 'lg:col-span-6',
    4: 'lg:col-span-4',
    3: 'lg:col-span-3',
  }
  const inputCls = 'w-full px-3 py-2 text-xs border border-slate-200 rounded-lg focus:outline-none focus:ring-2 focus:ring-blue-500 bg-white'

  // plain function (not a component) so inputs keep focus while typing
  const field = (f: { label: string; name: string; type?: string; span: number }) => (
    <div key={f.name} className={SPAN[f.span]}>
      <label className="text-xs font-medium text-slate-700 mb-1 block">{f.label}</label>
      <input
        type={f.type || 'text'}
        value={form[f.name] || ''}
        onChange={e => set(f.name, e.target.value)}
        className={inputCls}
      />
    </div>
  )

  const profileFields = (
    <>
      <div className={SPAN[4]}>
        <div className="flex items-center justify-between mb-1">
          <label className="text-xs font-medium text-slate-700">Company Identifier (ID) *</label>
          {!company && (
            <span className="text-[10px] font-bold text-blue-600 bg-blue-50 border border-blue-200 px-2 py-0.5 rounded-full inline-flex items-center gap-1">
              <Sparkles className="w-2.5 h-2.5 text-blue-500" /> Auto
            </span>
          )}
        </div>
        <div className="relative">
          <input
            type="text"
            required
            value={form.company_id || ''}
            onChange={e => set('company_id', e.target.value)}
            placeholder="e.g. AZC803"
            className="w-full px-3 py-2 text-xs font-mono font-bold text-blue-700 bg-blue-50/40 border border-blue-200 rounded-lg focus:outline-none focus:ring-2 focus:ring-blue-500"
          />
          {!company && form.company_id !== autoGeneratedId && (
            <button type="button" onClick={handleResetAutoId} title="Reset to next auto ID" className="absolute right-2 top-1/2 -translate-y-1/2 text-slate-400 hover:text-blue-600 p-1">
              <RefreshCw className="w-3 h-3" />
            </button>
          )}
        </div>
      </div>

      <div className={SPAN[4]}>
        <label className="text-xs font-medium text-slate-700 mb-1 block">Country of Origin / Nationality</label>
        <CountrySelect value={form.country_of_origin} onChange={v => set('country_of_origin', v)} />
      </div>

      <div className={SPAN[4]}>
        <label className="text-xs font-medium text-slate-700 mb-1 block">License Type</label>
        <select value={form.entity_type || ''} onChange={e => set('entity_type', e.target.value)} className={inputCls}>
          <option value="">Select license type</option>
          <option value="Trading License">Trading License</option>
          <option value="Service License">Service License</option>
        </select>
      </div>

      <div className={SPAN[12]}>
        <label className="text-xs font-medium text-slate-700 mb-1 block">Official Registered Name *</label>
        <input
          type="text"
          required
          value={form.company_name || ''}
          onChange={e => set('company_name', e.target.value)}
          placeholder="e.g. Gulf Trading & Contracting LLC"
          className={inputCls}
        />
      </div>

      <div className={SPAN[12]}>
        <label className="text-xs font-medium text-slate-700 mb-1 block">Service Type</label>
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
          {[
            { value: 'a2z', title: 'New Company', desc: 'We set up the whole company, stage by stage' },
            { value: 'renewal', title: 'Renewal / Other Service', desc: 'Existing company — renewal or other service only, no stage handoff' },
          ].map(opt => {
            const active = (form.service_type || 'a2z') === opt.value
            return (
              <button
                key={opt.value}
                type="button"
                onClick={() => set('service_type', opt.value)}
                className={`text-left p-3 rounded-lg border transition ${active ? 'border-blue-500 bg-blue-50 ring-1 ring-blue-500' : 'border-slate-200 bg-white hover:bg-slate-50'}`}
              >
                <div className={`text-xs font-bold ${active ? 'text-blue-700' : 'text-slate-800'}`}>{opt.title}</div>
                <div className="text-[10px] text-slate-500 mt-0.5">{opt.desc}</div>
              </button>
            )
          })}
        </div>
      </div>
    </>
  )

  type FieldSpec = { label: string; name: string; type?: string; span: number }
  const sections: { title: string; icon: any; custom?: React.ReactNode; fields?: FieldSpec[] }[] = [
    { title: 'Company Profile & Identification', icon: Building2, custom: profileFields },
    {
      title: 'Statutory & Legal Identifiers',
      icon: FileCheck,
      fields: [
        { label: 'Commercial Registration (CR) Number', name: 'cr_number', span: 4 },
        { label: 'CR Issue Date', name: 'cr_issue_date', type: 'date', span: 4 },
        { label: 'CR Expiration Date', name: 'cr_expire_date', type: 'date', span: 4 },
        { label: 'MISA License Number', name: 'misa_license_no', span: 4 },
        { label: 'MISA Issue Date', name: 'misa_issue_date', type: 'date', span: 4 },
        { label: 'MISA Expiration Date', name: 'misa_expire_date', type: 'date', span: 4 },
        { label: 'Tax Identification Number (TIN)', name: 'tin_number', span: 3 },
        { label: 'VAT Registration Number', name: 'vat_number', span: 3 },
        { label: 'Chamber of Commerce Ref', name: 'chamber_registration_no', span: 3 },
        { label: 'GOSI / Qiwa Compliance Status', name: 'gosi_qiwa_status', span: 3 },
      ],
    },
    {
      title: 'Headquarters & Official Communication',
      icon: PhoneCall,
      fields: [
        { label: 'Corporate Email', name: 'official_email', type: 'email', span: 4 },
        { label: 'Direct WhatsApp Contact', name: 'whatsapp_number', span: 4 },
        { label: 'National Address / Headquarters Location', name: 'national_address', span: 4 },
      ],
    },
    {
      title: 'Executive Leadership & Shareholders',
      icon: Users,
      fields: [
        { label: 'CEO / General Manager Name', name: 'ceo_gm_name', span: 3 },
        { label: 'National ID / Iqama Number', name: 'iqama_no', span: 3 },
        { label: 'Principal Shareholder Name', name: 'shareholders_name', span: 3 },
        { label: 'Shareholder Mobile', name: 'shareholder_phone', span: 3 },
      ],
    },
    {
      title: 'Banking & Treasury Accounts',
      icon: Landmark,
      fields: [
        { label: 'Depository Bank Name', name: 'bank_name', span: 3 },
        { label: 'Beneficiary Account Name', name: 'account_name', span: 3 },
        { label: 'Account Number', name: 'account_number', span: 3 },
        { label: 'IBAN / SWIFT Identifier', name: 'iban_swift', span: 3 },
      ],
    },
    {
      title: 'Administrative & Operational Controls',
      icon: Sliders,
      fields: [
        { label: 'Portal / Digital Credentials Reference', name: 'file_portal_login', span: 4 },
        { label: 'Operational Status', name: 'account_status', span: 4 },
        { label: 'Assigned Regional Office', name: 'assigned_office', span: 4 },
        { label: 'Cloud Document Folder (Google Drive)', name: 'drive_link', span: 6 },
        { label: 'Account Handler Officer', name: 'employee', span: 6 },
        { label: 'Confidential Internal Remarks', name: 'remarks', span: 12 },
      ],
    },
  ]

  return (
    <div className="w-full max-w-[2000px] mx-auto bg-white rounded-xl border border-slate-200 shadow-sm">
      <div className="flex items-center justify-between px-5 py-4 border-b border-slate-100">
        <div>
          <h2 className="text-base font-bold text-slate-900">
            {company ? 'Edit Corporate Profile' : 'Register Corporate Entity'}
          </h2>
          <p className="text-xs text-slate-400">Master record database</p>
        </div>
        <button onClick={onClose} title="Back to directory" className="p-1.5 hover:bg-slate-100 rounded-lg transition text-slate-400 hover:text-slate-600">
          <X className="w-5 h-5" />
        </button>
      </div>

      <form onSubmit={handleSubmit} className="p-4 sm:p-6 space-y-5">
        {sections.map(section => {
          const SectionIcon = section.icon
          return (
            <div key={section.title} className="bg-slate-50/60 border border-slate-200/80 rounded-xl p-4">
              <div className="flex items-center gap-2 mb-3 pb-2 border-b border-slate-200/60">
                <SectionIcon className="w-4 h-4 text-blue-600" />
                <h3 className="text-xs font-bold text-slate-800 uppercase tracking-wide">{section.title}</h3>
              </div>
              <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-12 gap-x-4 gap-y-3">
                {section.custom ?? section.fields?.map(field)}
              </div>
            </div>
          )
        })}

        <div className="flex gap-3 pt-3 border-t border-slate-100">
          {company && (
            <button
              type="button"
              onClick={handleDelete}
              className="px-4 py-2 border border-rose-200 text-rose-600 text-xs font-medium rounded-lg hover:bg-rose-50 transition flex items-center gap-1.5"
            >
              <Trash2 className="w-3.5 h-3.5" /> Delete Entity
            </button>
          )}
          <button
            type="button"
            onClick={onClose}
            className="flex-1 px-4 py-2 border border-slate-200 text-slate-600 text-xs font-medium rounded-lg hover:bg-slate-50 transition"
          >
            Cancel
          </button>
          <button
            type="submit"
            disabled={loading}
            className="flex-1 px-4 py-2 bg-blue-600 hover:bg-blue-700 text-white text-xs font-semibold rounded-lg transition flex items-center justify-center gap-2"
          >
            {loading ? <><Loader2 className="w-3.5 h-3.5 animate-spin" /> Saving...</> : (company ? 'Update Entity' : 'Create Entity Record')}
          </button>
        </div>
      </form>
    </div>
  )
}
